#!/usr/bin/env bash
#
# One-time setup for a fresh Aliyun ECS (Hong Kong) running Ubuntu 22.04/24.04 x86_64.
# Run AS ROOT on the server after SSHing in:
#
#   ssh root@<ECS_IP>
#   export REGISTRY_NS=<your-acr-namespace>              # e.g. liangpeter
#   export REGISTRY_USERNAME=<acr-username>              # optional now, can fill later
#   export REGISTRY_PASSWORD=<acr-login-password>        # optional now, can fill later
#   curl -fsSL https://raw.githubusercontent.com/liangpeter08/llamaOS/main/scripts/deploy/bootstrap.sh | bash
#
# Or clone first and run:  sudo bash scripts/deploy/bootstrap.sh
#
# It installs Docker, clones the repo to /opt/llamaos, adds swap for the small box,
# fixes bind-mount ownership, and (if registry creds are given) logs in. It does NOT
# create secrets or start the stack — run scripts/deploy/push-secrets.sh from your laptop,
# then scripts/deploy/deploy.sh (or let GitHub Actions do it).
set -euo pipefail

APP_DIR=/opt/llamaos
REPO_URL="${REPO_URL:-https://github.com/liangpeter08/llamaOS.git}"
BRANCH="${BRANCH:-main}"
REGISTRY="${REGISTRY:-registry.cn-hongkong.aliyuncs.com}"
REGISTRY_NS="${REGISTRY_NS:-}"
APP_UID=10001

log() { echo -e "\n\033[1;36m==> $*\033[0m"; }

if [ "$(id -u)" -ne 0 ]; then echo "run as root (sudo -i)"; exit 1; fi
if [ "$(uname -m)" != "x86_64" ]; then echo "this script assumes an x86_64 (amd64) ECS; found $(uname -m)"; exit 1; fi

log "Updating packages and installing prerequisites"
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y ca-certificates curl git ufw

if ! command -v docker >/dev/null 2>&1; then
  log "Installing Docker Engine + Compose plugin"
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker
docker --version
docker compose version

log "Ensuring swap exists (the stack wants 4-6 GB RAM; images are pulled, not built)"
MEM_MB=$(( $(grep MemTotal /proc/meminfo | awk '{print $2}') / 1024 ))
if [ "$MEM_MB" -lt 6000 ] && ! swapon --show | grep -q /swapfile; then
  fallocate -l 4G /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=4096
  chmod 600 /swapfile
  mkswap /swapfile >/dev/null
  swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  echo "swap added: $(swapon --show | grep /swapfile | awk '{print $3}')"
else
  echo "swap already present or host has >= 6 GB RAM"
fi
# Aliyun images ship vm.swappiness=0, which leaves swap unused until the OOM killer fires.
sysctl -w vm.swappiness=10 >/dev/null
echo 'vm.swappiness=10' > /etc/sysctl.d/99-llamaos-swap.conf

log "Cloning/updating $REPO_URL ($BRANCH) -> $APP_DIR"
if [ -d "$APP_DIR/.git" ]; then
  git -C "$APP_DIR" fetch --depth=1 origin "$BRANCH"
  git -C "$APP_DIR" checkout -q "$BRANCH"
  git -C "$APP_DIR" reset --hard "origin/$BRANCH"
else
  git clone --depth=1 --branch "$BRANCH" "$REPO_URL" "$APP_DIR"
fi
cd "$APP_DIR"

log "Fixing bind-mount ownership for the non-root container user (uid $APP_UID)"
mkdir -p "$APP_DIR/data"
# models/api compile drafts into strategies/ and cache models into data/
chown -R "$APP_UID:$APP_UID" "$APP_DIR/strategies" "$APP_DIR/data" || true
mkdir -p "$APP_DIR/secrets" "$APP_DIR/config"

if [ -n "$REGISTRY_NS" ]; then
  log "Writing /opt/llamaos/.env (registry namespace for compose image refs)"
  umask 077
  cat > "$APP_DIR/.env" <<EOF
# Generated by bootstrap.sh; compose reads this for docker-compose.prod.yml interpolation.
REGISTRY_NAMESPACE=$REGISTRY/$REGISTRY_NS
EOF
  chmod 600 "$APP_DIR/.env"

  mkdir -p /etc/llamaos
  if [ -n "${REGISTRY_USERNAME:-}" ] && [ -n "${REGISTRY_PASSWORD:-}" ]; then
    cat > /etc/llamaos/registry.env <<EOF
REGISTRY=$REGISTRY
REGISTRY_USERNAME=$REGISTRY_USERNAME
REGISTRY_PASSWORD=$REGISTRY_PASSWORD
EOF
    chmod 600 /etc/llamaos/registry.env
    echo "$REGISTRY_PASSWORD" | docker login "$REGISTRY" -u "$REGISTRY_USERNAME" --password-stdin
  else
    echo "Registry credentials not supplied; create /etc/llamaos/registry.env later and 'docker login'."
  fi
fi

log "Firewall: opening 22/80/443 (the Aliyun security group must also allow these)"
ufw allow 22/tcp  >/dev/null || true
ufw allow 80/tcp  >/dev/null || true
ufw allow 443/tcp >/dev/null || true
ufw --force enable >/dev/null 2>&1 || true

cat <<EOF

Bootstrap complete. Next:

1. From your LAPTOP (where the real secrets/*.env live), copy the gitignored secrets:
     REGISTRY_NS=$REGISTRY_NS bash scripts/deploy/push-secrets.sh root@<ECS_IP>
   (or copy each file yourself into /opt/llamaos/secrets and the two config yamls.)

2. Make sure the DNS A records for hesynth.xyz and www.hesynth.xyz point to this host,
   and the Aliyun security group allows inbound 22/80/443.

3. Deploy (or just push to main on GitHub and Actions will):
     bash $APP_DIR/scripts/deploy/deploy.sh latest

4. Create the first dashboard owner (prints the TOTP enrollment secret):
     cd $APP_DIR
     docker compose -f docker-compose.yml -f docker-compose.prod.yml exec api \\
       python -m services.api.create_owner --username admin
EOF
