"""Alpaca paper accounts the owner manages on the dashboard (System page).

Secrets are sealed to the broker: the API encrypts with the broker's public vault key (kv
'broker.vault_pub'); only processes holding BROKER_VAULT_KEY (secrets/broker.env: broker,
watchdog, host scripts) can decrypt. The API never reads a secret back.

Each account has its own book in schema acct_<id> (see db.ACCOUNT_TABLES): trades, positions,
equity history, funds, risk controls and which strategies are deployed. Switching the active
account points kv 'broker.account_schema' at it and bumps 'broker.account_rev'; the broker and
watchdog notice, exit with RESTART and come back on the new account (scripts/dev.py and Docker
restart them).
"""
from __future__ import annotations

import base64
import os
import re
import time

import httpx

from . import audit, db

PAPER_URL = "https://paper-api.alpaca.markets"
RESTART = 75  # exit code: restart me (account changed); not a crash
ENV_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "secrets", "broker.env")


def _b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


# ---------------------------------------------------------------- sealing (X25519 + HKDF + AES-GCM)
def _derive(shared: bytes, eph: bytes, pub: bytes) -> bytes:
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.kdf.hkdf import HKDF
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=eph + pub, info=b"llamaos broker account").derive(shared)


def _raw_pub(key) -> bytes:
    from cryptography.hazmat.primitives import serialization as S
    return key.public_bytes(S.Encoding.Raw, S.PublicFormat.Raw)


def seal(pub_b64: str, plaintext: str) -> str:
    from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    pub = base64.b64decode(pub_b64)
    eph = X25519PrivateKey.generate()
    key = _derive(eph.exchange(X25519PublicKey.from_public_bytes(pub)), _raw_pub(eph.public_key()), pub)
    nonce = os.urandom(12)
    return _b64(_raw_pub(eph.public_key()) + nonce + AESGCM(key).encrypt(nonce, plaintext.encode(), None))


def unseal(priv, token: str) -> str:
    from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PublicKey
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    raw = base64.b64decode(token)
    eph, nonce, ct = raw[:32], raw[32:44], raw[44:]
    key = _derive(priv.exchange(X25519PublicKey.from_public_bytes(eph)), eph, _raw_pub(priv.public_key()))
    return AESGCM(key).decrypt(nonce, ct, None).decode()


def vault_key(create: bool = False):
    """The broker's private vault key from BROKER_VAULT_KEY; with create, generate it into secrets/broker.env."""
    from cryptography.hazmat.primitives import serialization as S
    from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
    v = os.environ.get("BROKER_VAULT_KEY")
    if v:
        return X25519PrivateKey.from_private_bytes(base64.b64decode(v))
    if not create or not os.path.exists(ENV_FILE):
        return None
    k = X25519PrivateKey.generate()
    v = _b64(k.private_bytes(S.Encoding.Raw, S.PrivateFormat.Raw, S.NoEncryption()))
    with open(ENV_FILE) as f:
        text = f.read()
    if re.search(r"^BROKER_VAULT_KEY=\s*$", text, re.M):  # blank placeholder copied from the example
        text = re.sub(r"^BROKER_VAULT_KEY=\s*$", f"BROKER_VAULT_KEY={v}", text, count=1, flags=re.M)
    else:
        text += f"\n# Decrypts Alpaca accounts stored in the database (generated by the broker)\nBROKER_VAULT_KEY={v}\n"
    with open(ENV_FILE, "w") as f:
        f.write(text)
    os.environ["BROKER_VAULT_KEY"] = v
    return k


def publish(conn, priv) -> None:
    db.kv_set(conn, "broker.vault_pub", _b64(_raw_pub(priv.public_key())))


# ---------------------------------------------------------------- accounts
def mask(key_id: str) -> str:
    return key_id[:4] + "…" + key_id[-4:] if len(key_id) > 8 else "…"


def rev(conn) -> int:
    return int(db.kv_get(conn, "broker.account_rev") or 0)


def active(conn) -> dict | None:
    return db.row(conn, "SELECT * FROM broker_accounts WHERE active=1")


def listing(conn) -> list[dict]:
    out = []
    for r in db.rows(conn, "SELECT id,label,key_id,account_number,active,created_by,created_at,activated_at"
                           " FROM broker_accounts ORDER BY id"):
        r["key_id"] = mask(r["key_id"])
        out.append(r)
    return out


def credentials(conn=None) -> tuple[str | None, str | None, int, str, str | None]:
    """(key_id, secret, rev, source, schema) for the active dashboard account, else secrets/broker.env
    (whose book is the shared public schema)."""
    try:
        c = conn or db.get()
        with db.tx(c):  # one snapshot: keys, revision and schema all belong to the same account
            row, r = active(c), rev(c)
    except Exception:  # no database (tests, one-off scripts): the env file is the only source
        row, r = None, 0
    if row:
        priv = vault_key()
        if priv is None:
            raise ValueError("BROKER_VAULT_KEY is missing; it decrypts the Alpaca account stored in the database")
        return row["key_id"], unseal(priv, row["secret_sealed"]), r, "database", db.account_schema(row["id"])
    return os.environ.get("ALPACA_KEY_ID"), os.environ.get("ALPACA_SECRET_KEY"), r, "env", None


def sync_scope(conn) -> str | None:
    """Make sure the active account has its schema and that services point at it."""
    row = active(conn)
    schema = db.account_schema(row["id"]) if row else None
    if schema:
        db.ensure_account_schema(conn, schema)
    if db.kv_get(conn, "broker.account_schema") != schema:
        db.kv_set(conn, "broker.account_schema", schema)
    return schema


def check(key_id: str, secret: str) -> dict:
    """The paper account behind these keys, or ValueError. Live keys are rejected by the paper endpoint."""
    try:
        with httpx.Client(trust_env=False, timeout=10, follow_redirects=False) as client:
            r = client.get(PAPER_URL + "/v2/account", headers={"APCA-API-KEY-ID": key_id, "APCA-API-SECRET-KEY": secret})
    except httpx.HTTPError as e:
        raise ValueError(f"Alpaca unreachable ({type(e).__name__})")
    if r.status_code in (401, 403):
        raise ValueError("Alpaca rejected these keys (they must be paper-trading keys)")
    if r.status_code >= 400:
        raise ValueError(f"Alpaca returned HTTP {r.status_code}")
    return r.json()


def add(conn, label: str, key_id: str, secret: str, actor: str, verified: dict) -> int:
    pub = db.kv_get(conn, "broker.vault_pub")
    if not pub:
        raise ValueError("The broker has not published its vault key yet; start the paper broker once, then retry")
    if db.row(conn, "SELECT id FROM broker_accounts WHERE key_id=?", (key_id,)):
        raise ValueError("That key is already saved")
    aid = conn.insert("INSERT INTO broker_accounts(label,key_id,secret_sealed,account_number,created_by,created_at)"
                      " VALUES (?,?,?,?,?,?)", (label, key_id, seal(pub, secret), verified.get("account_number"), actor, time.time()))
    audit.log(conn, "broker_account.added", actor, {"id": aid, "label": label, "key_id": mask(key_id),
                                                    "account_number": verified.get("account_number")})
    return aid


def activate(conn, aid: int, actor: str) -> None:
    row = db.row(conn, "SELECT id,label,key_id,active FROM broker_accounts WHERE id=?", (aid,))
    if not row:
        raise ValueError("No such account")
    if row["active"]:
        raise ValueError("That account is already active")
    schema = db.account_schema(aid)
    new = db.ensure_account_schema(conn, schema)
    old = db.kv_get(conn, "broker.account_schema") or "public"
    with db.tx(conn):
        conn.execute("UPDATE broker_accounts SET active=0 WHERE active=1")
        conn.execute("UPDATE broker_accounts SET active=1, activated_at=? WHERE id=?", (time.time(), aid))
        # The old account's open intents were sized against its equity: they don't carry over.
        conn.execute(f"UPDATE {old}.intents SET status='expired', reason='broker account switched'"
                     " WHERE status IN ('pending','approved')")
        db.kv_set(conn, "broker.account_schema", schema)
        for k in ("account", "reconcile"):  # the new broker writes fresh ones within seconds
            conn.execute("DELETE FROM public.kv WHERE k=?", (k,))
        db.kv_set(conn, "broker.account_rev", rev(conn) + 1)
        audit.log(conn, "broker_account.activated", actor, {"id": aid, "label": row["label"], "key_id": mask(row["key_id"]),
                                                            "schema": schema, "new_book": new})


def remove(conn, aid: int, actor: str) -> None:
    row = db.row(conn, "SELECT id,label,key_id,active FROM broker_accounts WHERE id=?", (aid,))
    if not row:
        raise ValueError("No such account")
    if row["active"]:
        raise ValueError("Switch to another account before removing the active one")
    conn.execute("DELETE FROM broker_accounts WHERE id=?", (aid,))
    audit.log(conn, "broker_account.removed", actor, {"id": aid, "label": row["label"], "key_id": mask(row["key_id"])})


def adopt_env(conn, priv) -> None:
    """First run with dashboard accounts: save the secrets/broker.env keys as the active account."""
    key, secret = os.environ.get("ALPACA_KEY_ID"), os.environ.get("ALPACA_SECRET_KEY")
    if not key or not secret or db.row(conn, "SELECT id FROM broker_accounts LIMIT 1"):
        return
    try:
        acct = check(key, secret)
    except ValueError:
        return  # dead keys: let the owner add a working account instead
    with db.tx(conn):
        aid = conn.insert("INSERT INTO broker_accounts(label,key_id,secret_sealed,account_number,active,created_by,created_at,activated_at)"
                          " VALUES (?,?,?,?,1,?,?,?)", ("From broker.env", key, seal(_b64(_raw_pub(priv.public_key())), secret),
                                                       acct.get("account_number"), "broker", time.time(), time.time()))
        audit.log(conn, "broker_account.added", "broker", {"id": aid, "label": "From broker.env", "key_id": mask(key),
                                                          "account_number": acct.get("account_number")})
    sync_scope(conn)
